<?php
/**
 * Core class autoloader.
 *
 * WordPress core has no autoloader: historically every class file reachable on
 * a request was required eagerly from wp-settings.php, so its parse cost was
 * paid even on requests that never referenced it. This file registers a single
 * autoloader so that class, interface and trait files can instead be loaded the
 * first time the name they declare is actually referenced.
 *
 * Resolution is a direct lookup in a generated class map. No path is ever
 * derived from the requested name, and no filter, option, request value or
 * constant other than ABSPATH and WPINC can influence which file is loaded.
 *
 * The class map contract, which the generator and this consumer both honour:
 *
 * - The map lives beside this file and is always read from the hard-coded path
 *   `ABSPATH . WPINC . '/autoload-classmap.php'`.
 * - The map is a PHP file that returns an array keyed by the lower cased class,
 *   interface or trait name it declares. PHP resolves those names case
 *   insensitively, so a lower cased key and a lower cased lookup are what make
 *   `new wp_query()` and `new WP_Query()` reach the same file. A leading
 *   namespace separator is not part of the name PHP resolves either, so the
 *   lookup strips one before consulting the map.
 * - Every value is a repository-relative path that uses forward slashes, for
 *   example:
 *
 *       'wp_rest_posts_controller' => 'wp-includes/rest-api/endpoints/class-wp-rest-posts-controller.php',
 *
 * - A value is therefore resolved as `ABSPATH . $path`, and never as
 *   `ABSPATH . WPINC . '/' . $path`. Keeping the directory prefix inside the
 *   value is what lets one map work unchanged in both the development tree and
 *   the built tree without the map needing to know the value of WPINC, and it is
 *   what lets the map reach a class that lives outside `wp-includes/`.
 *
 * The map is generated by the `build:autoload-classmap` task in Gruntfile.js,
 * which only admits a file that declares exactly one symbol, runs nothing at its
 * own file scope, and whose parent class, interfaces and traits are themselves
 * either mapped, always loaded during the bootstrap, served by an autoloader
 * that is already registered, or internal to PHP. It must not be edited by hand.
 *
 * The map is not read when this file is required. It is loaded lazily on the
 * first autoload miss and then memoized for the rest of the request, so
 * registration costs nothing and requests that reference no mapped name,
 * including SHORTINIT requests, never touch the filesystem for it. When the map
 * is absent, does not return an array, or does not contain the requested name,
 * and when a mapped file has gone away, the autoloader silently does nothing so
 * that every other registered autoloader still gets its turn.
 *
 * @package WordPress
 * @since 7.0.0
 */

/**
 * Loads the file that declares a core class, interface or trait.
 *
 * Registered with spl_autoload_register(), so it runs only when a name that has
 * not been declared yet is referenced. Any name that is absent from the
 * generated class map is ignored without error, which leaves it to the other
 * registered autoloaders.
 *
 * The name is matched the way PHP resolves it rather than the way it happens to
 * be spelled: a leading namespace separator is dropped and the remainder is
 * lower cased, so `WP_Query`, `wp_query` and `\WP_Query` all reach the same
 * file.
 *
 * @since 7.0.0
 *
 * @param string $class_name Name of the class, interface or trait to load.
 * @return void
 */
function wp_autoload_class( $class_name ) {
	/*
	 * Null means the map has not been loaded yet, while an array - even an
	 * empty one - means the load has already been attempted. Distinguishing
	 * the two keeps the filesystem check below to one call per request even
	 * when the map is missing or legitimately empty.
	 */
	static $classmap = null;

	if ( null === $classmap ) {
		$classmap      = array();
		$classmap_file = ABSPATH . WPINC . '/autoload-classmap.php';

		if ( file_exists( $classmap_file ) ) {
			$map = require $classmap_file;

			// A map that does not return an array is treated as an empty map.
			if ( is_array( $map ) ) {
				$classmap = $map;
			}
		}
	}

	/*
	 * PHP passes the name as it was written at the reference site, so `WP_Query`
	 * and `wp_query` both arrive here even though they name one class. The map is
	 * keyed lower cased, so normalising here is what keeps a differently cased
	 * reference from being treated as an unknown name and silently skipped.
	 *
	 * PHP has already removed the one leading separator a fully qualified
	 * reference is written with, so a name that still starts with one reached
	 * spl_autoload_call() directly rather than through a reference. Exactly one
	 * more separator is removed for those callers, and no more: stripping a run of
	 * them would accept a name PHP itself cannot resolve.
	 */
	$name = '' !== $class_name && '\\' === $class_name[0] ? substr( $class_name, 1 ) : $class_name;
	$name = strtolower( $name );

	if ( ! isset( $classmap[ $name ] ) ) {
		return;
	}

	$file = ABSPATH . $classmap[ $name ];

	if ( ! file_exists( $file ) ) {
		return;
	}

	/*
	 * Loaded once rather than unconditionally. A name PHP cannot resolve, such as
	 * one written with a doubled leading separator, leaves the autoloader to run
	 * again for the same file when the caller falls through from class_exists() to
	 * interface_exists(), and a plain require would make that second pass a fatal
	 * redeclaration instead of a no-op.
	 */
	require_once $file;
}

spl_autoload_register( 'wp_autoload_class' );
